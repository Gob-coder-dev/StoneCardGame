"""Generate a phase-5 configuration with disjoint, equal-budget deck pools."""

import argparse
from pathlib import Path

import numpy as np
import yaml

from samstone_rl.bridge.godot_process import GodotProcess
from samstone_rl.decks.catalog import DeckCatalog
from samstone_rl.decks.generator import DeckGenerator
from samstone_rl.training.phase_five_decks import DECK_POOLS, FAMILY_COUNTS, validate_deck_pools
from samstone_rl.utils.checkpoints import atomic_text


class DeckList(list):
    """Keep one readable line per deck in the generated configuration."""


class ConfigDumper(yaml.SafeDumper):
    pass


ConfigDumper.add_representer(
    DeckList,
    lambda dumper, deck: dumper.represent_sequence("tag:yaml.org,2002:seq", deck, flow_style=True),
)


def make_pool(generator, god, ratio, size, seen, rng):
    catalog = generator.catalog
    decks = []
    for _ in range(128 * size):
        template = generator.random_candidate(god, rng).stone_ids
        deck = generator.match_budget(god, template, catalog.deck_budget, family_size=int(ratio))
        identity = catalog.canonicalize(deck)
        if identity not in seen:
            seen.add(identity)
            decks.append(DeckList(deck))
            if len(decks) == size:
                return decks
    raise ValueError(f"pas assez de compositions distinctes pour {god}, ratio {ratio}/8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", type=Path, default=Path("configs/ppo_self_play_80.yaml"))
    parser.add_argument("--output", type=Path, default=Path("configs/ppo_self_play_80_varied.yaml"))
    parser.add_argument("--seed", type=int, default=82731)
    args = parser.parse_args()
    config = yaml.safe_load(args.base.read_text(encoding="utf-8"))
    config["output_dir"] = "runs/ppo_self_play_80_varied"
    config["phase5"]["seed_base"] = 6200000000000
    env = config["environment"]
    with GodotProcess(godot_path=env.get("godot_path")) as bridge:
        catalog = DeckCatalog(bridge.deck_catalog())
    generator = DeckGenerator(catalog)
    rng = np.random.default_rng(args.seed)
    for scenario in env["scenarios"]:
        god = scenario["god"]
        seen = {catalog.canonicalize(scenario["deck"])}
        for name, count in zip(DECK_POOLS, (4, 2, 2), strict=True):
            scenario[name] = {
                ratio: make_pool(generator, god, ratio, count, seen, rng) for ratio in FAMILY_COUNTS
            }
        scenario["deck"] = scenario["training_decks"]["6"][0]
        print(f"{god}: {len(seen) - 1} decks", flush=True)
    validate_deck_pools(env)
    header = f"# Generated by generate_phase5_deck_pools.py with seed {args.seed}.\n"
    atomic_text(
        args.output, header + yaml.dump(config, Dumper=ConfigDumper, sort_keys=False, width=200)
    )
    print(f"Configuration validee par Godot: {args.output}", flush=True)


if __name__ == "__main__":
    main()
